'use client';
import { useEffect, useState } from 'react';
import { Sparkles, ArrowRight, BookOpen, TrendingUp, Activity, Lightbulb, CheckCircle, RefreshCw } from 'lucide-react';
import DashboardTopbar from '@/components/DashboardTopbar';
import styles from './ai.module.css';

const iconMap: Record<string, any> = { BookOpen, TrendingUp, Activity, Lightbulb, CheckCircle, Sparkles };
const priorityClass = (p: string) => p === 'High' ? 'badge-danger' : p === 'Medium' ? 'badge-warning' : 'badge-info';

export default function AIRecommendationsPage() {
  const [recs, setRecs] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);

  async function load() {
    const res = await fetch('/api/recommendations');
    const data = await res.json();
    setRecs(data.recommendations || []);
    setLoading(false);
  }

  async function regenerate() {
    setGenerating(true);
    await fetch('/api/recommendations', { method: 'POST' });
    await load();
    setGenerating(false);
  }

  useEffect(() => { load(); }, []);

  return (
    <div className={styles.page}>
      <DashboardTopbar title="AI Recommendations" />

      <div className={styles.header}>
        <div className={styles.headerIcon}><Sparkles size={22} color="var(--primary-light)" /></div>
        <div>
          <div className={styles.headerTitle}>{recs.length} Prioritized Improvement Areas</div>
          <div className={styles.headerSub}>Generated by LLM analysis of your documents, sensor data, and accreditation benchmarks</div>
        </div>
        <button className="btn btn-primary btn-sm" onClick={regenerate} disabled={generating}>
          {generating ? <RefreshCw size={13} className={styles.spin} /> : <Sparkles size={13} />}
          {generating ? 'Analyzing...' : 'Re-analyze'}
        </button>
      </div>

      {loading && <div style={{ color: 'var(--text-muted)', padding: 20 }}>Loading recommendations...</div>}

      {!loading && recs.length === 0 && (
        <div className={`glass-card ${styles.emptyState}`}>
          <Sparkles size={32} color="var(--primary-light)" />
          <div>No recommendations yet.</div>
          <div style={{ fontSize: '0.85rem', color: 'var(--text-muted)' }}>Upload and analyze documents first, then click Re-analyze.</div>
          <button className="btn btn-primary btn-sm" onClick={regenerate}>Generate Recommendations</button>
        </div>
      )}

      <div className={styles.suggestions}>
        {recs.map((s: any, i: number) => {
          const Icon = iconMap[s.category] || Sparkles;
          return (
            <div key={s._id || i} className={`glass-card ${styles.suggCard}`} style={{ borderLeft: `3px solid ${s.color || '#6366F1'}` }}>
              <div className={styles.suggTop}>
                <div className={styles.suggIcon} style={{ background: `${s.color || '#6366F1'}15` }}>
                  <Icon size={18} color={s.color || '#6366F1'} />
                </div>
                <div className={styles.suggInfo}>
                  <div className={styles.suggTitle}>{s.title}</div>
                  <div className={styles.suggWhy}>{s.why}</div>
                </div>
                <div style={{ display: 'flex', flexDirection: 'column', gap: 6, alignItems: 'flex-end' }}>
                  <span className={`badge ${priorityClass(s.priority)}`}>{s.priority} Priority</span>
                  <span className="badge badge-success">{s.impact}</span>
                </div>
              </div>
              <div className={styles.actions}>
                <div className={styles.actionsLabel}>Action Items:</div>
                {s.actions?.map((a: string, j: number) => (
                  <div key={j} className={styles.actionItem}>
                    <ArrowRight size={12} color="var(--primary-light)" /> {a}
                  </div>
                ))}
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}
